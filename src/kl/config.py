from pathlib import Path


def _load_dotenv(path: Path) -> None:
    """Read KEY=VALUE lines from a .env file into os.environ without overriding variables already set.
    No dependency, no interpolation; '#' lines and blanks are skipped. Values are never logged."""
    if not path.is_file():
        return
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        key, _, value = line.partition("=")
        key, value = key.strip(), value.split("#", 1)[0].strip().strip('"').strip("'")
        if key and value and key not in os.environ:
            os.environ[key] = value


